/**
 * Always-visible skill XP bar sitting right above the vanilla experience bar,
 * showing the most recent skill that gained XP. Kept vanilla-slick: just the
 * bar and the skill level in the middle, drawn fully opaque like the vanilla
 * experience bar. On each XP gain two icons of the skill's tool converge into
 * the bar (fading in), then the bar grows.
 *
 * <p>The fill is styled like vanilla's own progress bar (border, segment notches,
 * shaded rows, glint) in the skill's colour. It is two of OUR sprites, generated by
 * {@code docs/art/make_skill_bar.py}: a GREYSCALE body drawn with the skill colour as
 * the vertex tint (GPU multiply), then a white-with-alpha sheen drawn untinted on top.
 * Grey, not vanilla's green progress sprite: tint x green turns every non-green skill
 * muddy. The sheen exists because a multiply can only darken — without it nothing on
 * the bar could be lighter than the skill colour itself. Background stays vanilla's
 * sprite, referenced, never copied; the body's notches sit in the background's columns.
 *
 * <p>Four small fill animations, all tuned in the constants block below: a glint on the
 * leading edge when XP lands, a brief brightening of a cell the fill just completed, ONE
 * gentle pulse per XP value in the last tenth of a level, and a colour/fill crossfade when
 * the shown skill changes. Shared math; only {@link #blitFill} forks per node.
 */
